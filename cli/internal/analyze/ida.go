package analyze

import (
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"time"

	"twdll/cli/internal/ui"
)

// FindIDAExecutable locates idat.exe / idat64.exe or ida.exe in the given directory.
func FindIDAExecutable(idaDir string, is64Bit bool) (string, error) {
	if idaDir == "" {
		return "", fmt.Errorf("ida_dir is not configured in twdll.toml")
	}

	var candidates []string
	if runtime.GOOS == "windows" {
		if is64Bit {
			candidates = []string{
				filepath.Join(idaDir, "idat64.exe"),
				filepath.Join(idaDir, "idat.exe"), // IDA 9.x unified
				filepath.Join(idaDir, "ida64.exe"),
				filepath.Join(idaDir, "ida.exe"),
			}
		} else {
			candidates = []string{
				filepath.Join(idaDir, "idat.exe"),
				filepath.Join(idaDir, "idat64.exe"),
				filepath.Join(idaDir, "ida.exe"),
				filepath.Join(idaDir, "ida64.exe"),
			}
		}
	} else {
		if is64Bit {
			candidates = []string{
				filepath.Join(idaDir, "idat64"),
				filepath.Join(idaDir, "idat"),
				filepath.Join(idaDir, "ida64"),
				filepath.Join(idaDir, "ida"),
			}
		} else {
			candidates = []string{
				filepath.Join(idaDir, "idat"),
				filepath.Join(idaDir, "idat64"),
				filepath.Join(idaDir, "ida"),
				filepath.Join(idaDir, "ida64"),
			}
		}
	}

	for _, c := range candidates {
		if stat, err := os.Stat(c); err == nil && !stat.IsDir() {
			return c, nil
		}
	}
	return "", fmt.Errorf("neither idat nor ida executable found in %s", idaDir)
}

// RunIDABatch executes headless IDA Pro in batch mode (-A -B).
func RunIDABatch(ctx context.Context, idaDir string, item Item, slot *ui.TaskSlot, printer *ui.Printer) error {
	exePath, err := FindIDAExecutable(idaDir, item.Target == "attila_64")
	if err != nil {
		return err
	}

	if err := os.MkdirAll(item.OutputDir, 0o755); err != nil {
		return fmt.Errorf("create output dir: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(item.LogFile), 0o755); err != nil {
		return fmt.Errorf("create log dir: %w", err)
	}

	startTime := time.Now()
	cleanLog := filepath.ToSlash(item.LogFile)
	if slot == nil && printer != nil {
		printer.Info("  [ida] Analyzing %s (logs: %s)...", printer.Bold(string(item.Target)), printer.Dim(cleanLog))
	}

	// idat.exe -A -B -o<dest_db> -L<log_file> <source_binary>
	args := []string{
		"-A",
		"-B",
		"-o" + item.MarkerFile,
		"-L" + item.LogFile,
		item.BinaryPath,
	}

	cmd := exec.CommandContext(ctx, exePath, args...)

	if err := cmd.Start(); err != nil {
		return fmt.Errorf("start ida: %w", err)
	}

	if slot != nil && cmd.Process != nil {
		slot.SetPID(cmd.Process.Pid)
	}

	runErr := cmd.Wait()
	if runErr != nil {
		return fmt.Errorf("ida batch analysis failed for %s (see %s): %w", item.Target, item.LogFile, runErr)
	}

	// Clean up intermediate .asm file generated by -B
	asmFile := filepath.Join(item.OutputDir, string(item.Target)+".asm")
	_ = os.Remove(asmFile)

	// Verify database file exists and is not empty
	stat, err := os.Stat(item.MarkerFile)
	if err != nil || stat.Size() == 0 {
		return fmt.Errorf("ida finished with exit 0 but database file is missing or empty: %s", item.MarkerFile)
	}

	elapsed := time.Since(startTime).Round(time.Second)
	sizeMB := float64(stat.Size()) / (1024 * 1024)
	finishMsg := fmt.Sprintf("  [ida] %s finished in %s (%.1f MB database)", printer.Green(string(item.Target)), elapsed, sizeMB)
	if slot != nil {
		if slot.Total > 1 {
			finishMsg = fmt.Sprintf("  [%d/%d] [ida] %s finished in %s (%.1f MB database)", slot.Index, slot.Total, printer.Green(string(item.Target)), elapsed, sizeMB)
		}
		slot.Finish(finishMsg)
	} else if printer != nil {
		printer.Info("%s", finishMsg)
	}
	return nil
}
